function buildEntry(c: typeof FALLBACK_COUNTRIES[0]): ApiCountryCode {
  return {
    iso2: c.iso2,
    defaultName: c.name,
    countryCode: c.code,
    patterns: c.patterns,
  };
}

export default function getFallbackCountryList(): {
  phoneCodes: ApiCountryCode[];
  general: ApiCountry[];
} {
  const phoneCodes = FALLBACK_COUNTRIES
    .map(buildEntry)
    .sort((a, b) => a.defaultName.localeCompare(b.defaultName));

  const general = phoneCodes.map((c) => ({
    iso2: c.iso2,
    defaultName: c.defaultName,
    name: c.name,
  }));

  return { phoneCodes, general };
}
